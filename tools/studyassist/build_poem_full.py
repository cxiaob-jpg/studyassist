PUNCT = re.compile(r"[，。？！；：、“”‘’（）\s]")

def norm(s):
    return PUNCT.sub('', s)

fails = []
added = 0
for f in sorted(glob.glob(f"{DATA}/recite/chinese/g*.json")):
    d = json.load(open(f))
    vol_cards = d["cards"]
    # collect poem groups in this volume
    groups = {}
    for c in vol_cards:
        if c["kind"] != "poem":
            continue
        pid = re.match(r"(cnc_p\d+)", c["id"]).group(1)
        groups.setdefault(pid, []).append(c)
    # remove old poem_full cards (idempotent)
    vol_cards[:] = [c for c in vol_cards if c["kind"] != "poem_full"]
    for pid, cards in groups.items():
        if pid not in POEMS:
            fails.append(f"{os.path.basename(f)} {pid} 缺全文")
            continue
        title, author, dynasty, text = POEMS[pid]
        ntext = norm(text)
        label = f"《{title}》"
        if dynasty:
            label += f"\n{dynasty}·{author}"
        elif author and author not in ("识字韵文", "民谣", "《三字经》", "《增广贤文》", "《诗经》", "《古诗十九首》", "鲁迅"):
            label += f"\n{author}"
        for c in cards:
            for half in (c["front"], c["back"]):
                nh = norm(half)
                if nh and nh not in ntext:
                    fails.append(f"{os.path.basename(f)} {pid} {title}: 半句不在全文[{half}]")
        vol_cards.append({
            "id": pid + "_full",
            "kind": "poem_full",
            "front": label,
            "back": text.replace("。\n", "。\n").replace("？\n", "？\n"),
            "note": (f"{dynasty}·{author}" if dynasty else author) if author else "",
        })
        added += 1
    json.dump(d, open(f, "w"), ensure_ascii=False, indent=1)

print("新增 poem_full 卡:", added)
if fails:
    print("校验失败:")
    for x in fails: print("  ", x)
else:
    print("全部半句校验 PASS")
